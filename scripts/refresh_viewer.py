"""Regenerate the vendored ``viewer.js`` from the installed trame-vtk.

``trame_pyvista/static/viewer.js`` is a committed, hand-reviewable artifact:
the ``OfflineLocalView`` library bundle that ships inside trame-vtk
(``trame_vtk/tools/static_viewer.html``) with the standalone-page auto boot
(URL-param load + drag-and-drop file zone) stripped so it does not mutate the
host notebook page. This script is the sole owner of that transformation.
Run it after a trame-vtk version bump, then commit the refreshed file.

The output is deterministic (no timestamps), so CI can regenerate it against
the pinned trame-vtk and ``git diff --exit-code`` it to catch drift.
"""

from __future__ import annotations

import importlib.metadata
from pathlib import Path
import re

OUTPUT_PATH = Path(__file__).resolve().parent.parent / 'trame_pyvista' / 'static' / 'viewer.js'

# Cosmetic marker kept for parity with the historical hand-patched file and
# human readability; sits immediately before the public API literal.
BOOT_COMMENT = (
    '/* trame-pyvista: standalone auto-load/file-drop boot disabled for in-notebook embedding */'
)

# Matches trame's first inline <script>: make a `global` object available to
# the bundle, which expects one.
GLOBAL_INIT = """if (typeof globalThis !== "undefined") {
  globalThis.global = globalThis.global || {};
}"""


def _strip_bootstrap(module_script: str) -> str:
    """Keep the library + public API, drop the standalone auto boot.

    Anchors on the stable public API name ``window.OfflineLocalView=``:
    everything before it is the library (minus the trailing standalone
    auto-boot), and the API object literal plus its trailing ``;`` is the
    public entry point we must preserve.
    """
    anchor = 'window.OfflineLocalView='
    try:
        i = module_script.index(anchor)
    except ValueError:
        msg = (
            'trame-vtk renamed or removed `window.OfflineLocalView=`; '
            'update the anchor in scripts/refresh_viewer.py.'
        )
        raise SystemExit(msg) from None

    # Brace-match the ``window.OfflineLocalView={...}`` object literal.
    brace = module_script.index('{', i)
    depth = 0
    end = None
    for p in range(brace, len(module_script)):
        ch = module_script[p]
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                end = p
                break
    if end is None:
        msg = 'Could not brace-match the `window.OfflineLocalView` object literal.'
        raise SystemExit(msg)
    end_excl = end + 1
    if end_excl < len(module_script) and module_script[end_excl] == ';':
        end_excl += 1
    api_stmt = module_script[i:end_excl]

    # Keep the library up to the API, then drop the trailing standalone
    # auto-boot (the last `setTimeout(...)` call and the boot it schedules).
    lib = module_script[:i]
    boot = lib.rfind('setTimeout(')
    if boot != -1:
        lib = lib[:boot]

    return lib + BOOT_COMMENT + api_stmt


def _trame_vtk_version() -> str:
    """Return the installed trame-vtk version, or ``unknown`` if not found."""
    try:
        return importlib.metadata.version('trame-vtk')
    except importlib.metadata.PackageNotFoundError:
        return 'unknown'


def main() -> None:
    """Read the trame-vtk viewer HTML and write the stripped ``viewer.js``."""
    from trame_vtk.tools.vtksz2html import HTML_VIEWER_PATH

    html = HTML_VIEWER_PATH.read_text(encoding='utf-8')
    match = re.search(r'<script type="module">(.*?)</script>', html, re.DOTALL)
    if match is None:
        msg = (
            f'No inline <script type="module"> in {HTML_VIEWER_PATH}; '
            'trame-vtk restructured its viewer HTML? Pin trame-vtk to a working version.'
        )
        raise SystemExit(msg)

    body = _strip_bootstrap(match.group(1))

    header = (
        '// Generated by scripts/refresh_viewer.py — do not edit by hand.\n'
        f'// Source: trame_vtk/tools/static_viewer.html (trame-vtk {_trame_vtk_version()})\n'
        '// Regenerate with: just refresh-viewer   (or: python scripts/refresh_viewer.py)\n'
    )
    output = f'{header}{GLOBAL_INIT}\n{body}\n'
    OUTPUT_PATH.write_text(output, encoding='utf-8')
    print(f'Wrote {OUTPUT_PATH} ({len(output.encode("utf-8"))} bytes)')  # noqa: T201


if __name__ == '__main__':
    main()
